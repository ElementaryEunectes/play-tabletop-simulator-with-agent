// verify_f8.js - does the bridge in tts/lua/dsh_global.lua actually define everything it registers?
//
// WHY THIS EXISTS (F8, 2026-08-10): the v14 primitives block was spliced inside setCount(), so the
// chunk compiled, the handlers table was built, and the names it called had never been assigned.
// Every offline gate was green - the primitives test starts extracting BELOW the splice, so it
// walked straight past the dead region. "All gates green" and "the bridge is loadable" are
// different claims; this checks the second one.
//
// HOW: the bridge defines its handlers as `DSH_<name> = function` at chunk level. After loading the
// chunk in a Lua VM, every registered name must exist as a global. A missing one means the
// definition is nested inside something that did not run - exactly F8.
//
//   node tts/tools/verify_f8.js [statusFile]
//   exit 0 = every definition is reachable after load; 1 = at least one is missing or it did not load
//   With statusFile, the same verdict is written there as `VERDICT=PASS|FAIL`. WHY: a caller that
//   re-enters through cmd.exe or a wrapper can lose this process's exit code, and a gate that reads
//   the code alone then reports a false failure (or a false pass). The file is the durable channel.
const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const SRC = path.join(__dirname, '..', 'lua', 'dsh_global.lua');
const text = fs.readFileSync(SRC, 'utf8').replace(/\r\n/g, '\n');

// the appended bridge starts at its banner; before that is the game's own module half
const start = text.split('\n').findIndex((l) => l.includes('DSH bridge (appended)'));
const bridge = start >= 0 ? text.split('\n').slice(start + 1).join('\n') : text;

// Every definition the bridge makes at column 0: `local X = function`, `local function X` and
// `DSH_X = function`. After the chunk has loaded, each one must exist in scope. A name that is
// missing was defined inside something that never ran - which is exactly F8 (a missing `end`
// turned 250 lines into the body of setCount(), and the names registered fine but stayed nil).
const decls = [];
{
    const rows = bridge.split('\n');
    for (let i = 0; i < rows.length; i++) {
        const t = rows[i];
        let nm = null;
        let kind = null;
        let mm = /^local\s+function\s+(\w+)\s*\(/.exec(t);
        if (mm) { nm = mm[1]; kind = 'local_function'; }
        if (!nm) { mm = /^local\s+(\w+)\s*=\s*function/.exec(t); if (mm) { nm = mm[1]; kind = 'local_assign'; } }
        if (!nm) { mm = /^(DSH_\w+)\s*=\s*function/.exec(t); if (mm) { nm = mm[1]; kind = 'global_assign'; } }
        if (nm) decls.push({ line: i + 1, name: nm, kind: kind });
    }
}

// fold the multi-line body away, then append one check per definition: read the DEDICATED value the
// definition assigns, not the name (a wrong name and a dead definition look identical otherwise)
const looked = bridge
    .replace(/local\s+function\s+(\w+)\s*\(([^)]*)\)/g, 'local $1 = function($2)')
    .replace(/^(DSH_\w+)\s*=\s*function/gm, 'local $1 = function');

const header = [
    '-- GENERATED by tts/tools/verify_f8.js: the bridge alone plus stub TTS API.',
    'local sent = {}',
    'function getSeatedPlayers() return { "Teal" } end',
    'Player = { Teal = { color = "Teal", getHandCount = function() return 0 end } }',
    'Turns = { getTurnOrder = function() return { "Teal" } end }',
    'function getObjectFromGUID(g) return nil end',
    'function getObjects() return {} end',
    'function broadcastToAll() end',
    'function spawnObject(t) return nil end',
    'function spawnObjectJSON(t) return nil end',
    'function sendExternalMessage(t) table.insert(sent, t) end',
    'onLoad = nil',
    'local __dsh_prev_onLoad = onLoad',
].join('\n');

const checks = decls.map((d, i) => {
    const probe = '__DEF' + i;
    return { d, probe };
}).filter((c) => c.d.kind !== 'global_assign');

const inject = checks.map((c) => c.probe + ' = ' + c.d.name).join('\n');
const report = checks.map((c) =>
    'if type(' + c.probe + ') ~= "function" then missing[#missing+1] = "' + c.d.name + ' (line ' + c.d.line + ', ' + c.d.kind + ')" end'
).join('\n');

const footer = [
    'local missing = {}',
    inject,
    report,
    'print("DEFINITIONS=" .. ' + checks.length + ' .. " MISSING=" .. #missing ..',
    '      (#missing > 0 and ("\\n  " .. table.concat(missing, "\\n  ")) or " -> none"))',
    'os.exit(#missing == 0 and 0 or 1)',
].join('\n');

// WHY cache\, NOT local\scratch\ AND NOT tts\tests\ (measured 2026-10-13, on this repository's very first
// CI run): `local/` is gitignored, so a fresh clone has no `local\scratch` - this reachable-definitions
// check died with ENOENT and the gate dutifully reported FAIL, which reads as "the bridge is broken".
// It is the same class of defect as gate 6's missing fengari: a gate whose own scratch space lives
// outside the repository cannot run for anybody else. And a scratch file written INTO the tracked tree
// (`tts\tests\`) is only cleaned up if nothing crashes on the way. So both live in `cache\`, which this
// creates if absent - the same directory `run_all.ps1` puts its per-gate logs in.
const cacheDir = path.join(__dirname, '..', '..', 'cache');
fs.mkdirSync(cacheDir, { recursive: true });
const tmp = path.join(cacheDir, '_verify_f8.lua');
fs.writeFileSync(tmp, header + '\n' + looked + '\n' + footer + '\n', 'utf8');

const outFile = path.join(cacheDir, 'verify_f8_out.txt');
spawnSync(process.execPath, [path.join(__dirname, 'run_and_capture.js'), tmp, outFile], { stdio: 'ignore' });
const out = fs.readFileSync(outFile, 'utf8').trim();
fs.unlinkSync(tmp);
// run_and_capture writes "__EXIT=<status>"; that is the Lua child's own verdict. Read the COUNTS,
// not the exit code alone: a caller that only checks the code gets a green light for output that
// never arrived (the empty-output trap this repository already paid for).
const child = /__EXIT=(\d+)/.exec(out);
const counts = /DEFINITIONS=(\d+) MISSING=(\d+)/.exec(out);
const loaded = child !== null && Number(child[1]) === 0;
const allThere = counts !== null && Number(counts[2]) === 0 && Number(counts[1]) > 0;
console.log(out);
const verdict = loaded && allThere ? 'PASS' : 'FAIL';
console.log('VERDICT: ' + verdict +
            (counts ? ' - ' + counts[1] + ' definitions, ' + counts[2] + ' missing' : ' - bridge did not load'));
if (process.argv[2]) fs.writeFileSync(process.argv[2], 'VERDICT=' + verdict + '\n', 'utf8');
process.exit(verdict === 'PASS' ? 0 : 1);
