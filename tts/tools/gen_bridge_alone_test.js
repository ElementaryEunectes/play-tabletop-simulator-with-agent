// gen_bridge_alone_test.js - run ONLY the bridge (as the game has it) in a Lua VM and ask its own
// `probe` command what is bound.
//
// Extracted from the RUNNING script (local/scratch/running_global.lua) so it is exactly the bytes
// the game loaded, minus the module half that precedes it. Stubs cover only what the bridge touches
// at load time. This answers "is players nil here too?" without another bake/reload cycle.
// One-off: deleted after use.
const fs = require('fs');
const path = require('path');

const SRC = process.argv[2] || 'local/scratch/running_global.lua';
const running = fs.readFileSync(SRC, 'utf8');
const lines = running.split('\n');
// Either the full running script (module + bridge) or a bare bridge file.
let start = lines.findIndex((l) => l.includes('DSH bridge (appended)'));
const bridge = (start >= 0 ? lines.slice(start + 1) : lines).join('\n');

const header = [
    '-- GENERATED by gen_bridge_alone_test.js: the bridge alone, plus stub TTS API.',
    'local sent = {}',
    'function getSeatedPlayers() return { "Teal", "Brown" } end',
    'Player = {}',
    'Player.Teal = { color = "Teal", steam_name = "me", host = true, admin = true, seated = true, blindfolded = false }',
    'Player.Brown = { color = "Brown", steam_name = "you", host = false, admin = false, seated = true, blindfolded = false }',
    'Player.Teal.getHandCount = function() return 3 end',
    'Player.Brown.getHandCount = function() return 1 end',
    'Turns = {}',
    'Turns.getTurnOrder = function() return { "Teal", "Brown" } end',
    'function getObjectFromGUID(g) return nil end',
    'function getObjects() return {} end',
    'function broadcastToAll() end',
    'function spawnObject(t) return nil end',
    'function spawnObjectJSON(t) return nil end',
    'function sendExternalMessage(t) table.insert(sent, t) end',
    'onLoad = nil',
].join('\n');

const footer = [
    '',
    '-- call the command layer exactly like the bridge does for ds.ps1 -Do players',
    'if type(onExternalMessage) ~= "function" then print("FAIL onExternalMessage missing"); os.exit(1) end',
    '-- Lua itself answers whether the LOCAL is in scope here (this footer runs in the same chunk).',
    'print("SCOPE hand=" .. type(hand) .. " takeOne=" .. type(takeOne) .. " players=" .. type(players) ..',
    '      " DSH_dbg=" .. tostring(DSH_dbg) .. " TRACE=" .. tostring(TRACE1) .. "/" .. tostring(TRACE2))',
    'onExternalMessage({ cmd = "players" })',
    'local last = sent[#sent]',
    'if last == nil then print("FAIL no reply"); os.exit(1) end',
    'print("REPLY ok=" .. tostring(last.ok) .. " cmd=" .. tostring(last.cmd) .. " count=" .. tostring(last.count))',
    'print("REPLY seats=" .. tostring(last.seats and last.seats[1]))',
    'if last.err then print("REPLY err=" .. tostring(last.err)) end',
    'os.exit(0)',
].join('\n');

const out = header + '\n' + bridge + '\n' + footer + '\n';
fs.writeFileSync(path.join(__dirname, '..', 'tests', 'gen_bridge_alone.lua'), out, 'utf8');
console.log('wrote gen_bridge_alone.lua (' + out.split('\n').length + ' lines)');
