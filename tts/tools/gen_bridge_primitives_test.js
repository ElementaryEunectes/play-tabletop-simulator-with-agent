function between(startAnchor, endAnchor, what) {
    const i = raw.indexOf(startAnchor);
    if (i < 0) { console.error('EXTRACT MISS (start): ' + what); process.exit(1); }
    const j = raw.indexOf(endAnchor, i + startAnchor.length);
    if (j < 0) { console.error('EXTRACT MISS (end): ' + what); process.exit(1); }
    return raw.slice(i, j);
}
